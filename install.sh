#!/bin/bash
# omarchy-captcha installer.
#
# Installs the two CLI tools to /usr/local/bin (needs sudo) and symlinks the
# qute-captcha userscript into the qutebrowser profile, then writes the keybinding
# fragment. Idempotent: re-run it after a git pull.
set -euo pipefail

PLUGIN_DIR="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"
QUTE_CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/qutebrowser"
QUTE_DATA_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/qutebrowser"
BIN_DIR="/usr/local/bin"

printf 'omarchy-captcha: installing from %s\n' "$PLUGIN_DIR"

# --- CLI tools -> /usr/local/bin -----------------------------------------
for tool in "$PLUGIN_DIR"/bin/omarchy-captcha-*; do
  name="$(basename "$tool")"
  chmod +x "$tool"
  dest="$BIN_DIR/$name"
  if [[ -L $dest ]] && [[ "$(readlink -f "$dest")" == "$(readlink -f "$tool")" ]]; then
    printf '  %s already linked\n' "$name"
    continue
  fi
  sudo ln -sf "$tool" "$dest"
  printf '  linked %s -> %s\n' "$name" "$dest"
done

# --- userscript -> both qutebrowser userscript dirs ----------------------
mkdir -p "$QUTE_DATA_DIR/userscripts" "$QUTE_CONFIG_DIR/userscripts"
chmod +x "$PLUGIN_DIR/userscripts/qute-captcha"
ln -sf "$PLUGIN_DIR/userscripts/qute-captcha" "$QUTE_DATA_DIR/userscripts/qute-captcha"
ln -sf "$PLUGIN_DIR/userscripts/qute-captcha" "$QUTE_CONFIG_DIR/userscripts/qute-captcha"
printf '  linked qute-captcha userscript\n'

# --- keybindings fragment -------------------------------------------------
FRAGMENT="$QUTE_CONFIG_DIR/captcha-bindings.py"
CONFIG_PY="$QUTE_CONFIG_DIR/config.py"
# qutebrowser sources exactly one config.py, so a fragment needs one source line for the
# bindings to exist. Follow a symlinked config.py (omarchy-qutebrowser owns it that way) to
# the file that actually defines the config and add the marked line there, so the plugin
# wires itself with no manual step. Idempotent.
TARGET_PY="$CONFIG_PY"
if [[ -L $CONFIG_PY ]]; then
  TARGET_PY="$(readlink -f "$CONFIG_PY")"
  printf '  config.py is a symlink -> %s\n' "$TARGET_PY"
fi

# The prefix is ",v" on purpose. qutebrowser has NO timeout on a partial match, so a binding whose
# first key is itself bound - e.g. ,cc while ,c is reader-factcheck - makes ",c" stop firing and
# swallows the next keypress. Nothing logs an error; the shortcut just goes dead. ",v" is bound to
# nothing on its own, so ,vc/,va/,vs cannot break anything.
STAGE=$(mktemp)
trap 'rm -f "$STAGE"' EXIT
cat > "$STAGE" <<'PY'
# omarchy-captcha keybindings - generated by install.sh
config.bind(",vc", "spawn --userscript qute-captcha", mode="normal")          # noqa: F821
config.bind(",va", "spawn --userscript qute-captcha audio", mode="normal")    # noqa: F821
config.bind(",vs", "spawn --userscript qute-captcha status", mode="normal")   # noqa: F821
PY

CHECK=(--fragment "$STAGE")
if [[ -f $TARGET_PY ]]; then
  CHECK+=(--config "$TARGET_PY")
fi
if ! python3 "$PLUGIN_DIR/tools/check_bindings.py" "${CHECK[@]}"; then
  printf 'install.sh: refusing to install keybindings that collide with %s\n' "$TARGET_PY" >&2
  exit 1
fi
mv "$STAGE" "$FRAGMENT"
printf '  wrote %s\n' "$FRAGMENT"
if [[ -f $TARGET_PY ]]; then
  if grep -q 'captcha-bindings.py' "$TARGET_PY"; then
    printf '  config.py already sources the fragment\n'
  else
    printf '\nconfig.source("captcha-bindings.py")\n' >> "$TARGET_PY"
    printf '  added the source line to %s\n' "$TARGET_PY"
  fi
else
  printf '\nNOTE: no %s found. Add this line where your config is loaded:\n' "$CONFIG_PY"
  printf '    config.source("captcha-bindings.py")\n'
fi

printf '\nDone. Bindings: ,vc solve  ,va audio  ,vs status\n'
printf 'Dependencies: tesseract (required for OCR); ffmpeg + a local STT backend for audio.\n'
