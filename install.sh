#!/bin/bash
# omarchy-captcha installer.
#
# Installs the two CLI tools to /usr/local/bin (needs sudo) and symlinks the
# qute-captcha userscript into the qutebrowser profile, then writes the keybinding
# fragment. Idempotent: re-run it after a git pull.
#
#   ./install.sh                 install / update everything
#   ./install.sh --uninstall     remove what this script installed, and only that
#
# OMARCHY_CAPTCHA_BIN overrides the bin directory (default /usr/local/bin). --uninstall reverses
# every artifact install.sh creates: the /usr/local/bin symlinks, the two userscript symlinks, the
# generated bindings fragment, and the `config.source(...)` line it appends to config.py.
set -euo pipefail

PLUGIN_DIR="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"
QUTE_CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/qutebrowser"
QUTE_DATA_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/qutebrowser"
BIN_DIR="${OMARCHY_CAPTCHA_BIN:-/usr/local/bin}"
FRAGMENT="$QUTE_CONFIG_DIR/captcha-bindings.py"
CONFIG_PY="$QUTE_CONFIG_DIR/config.py"
SOURCE_LINE='config.source("captcha-bindings.py")'
FRAGMENT_MARKER='# omarchy-captcha keybindings - generated by install.sh'

say() { printf '  %s\n' "$1"; }
warn() { printf 'WARNING: %s\n' "$1" >&2; }

unlink_ours() {  # unlink_ours <dest> <source it must point at>
  local dest="$1" source="$2"
  if [[ -L $dest ]] && [[ "$(readlink -f "$dest")" == "$(readlink -f "$source")" ]]; then
    rm -f "$dest"
    say "removed $dest"
  elif [[ -e $dest ]]; then
    warn "$dest is not a link into this checkout — left alone."
  fi
}

uninstall() {
  echo "omarchy-captcha: uninstalling"

  # --- CLI tools ----------------------------------------------------------
  # Only our own symlink: a real file (or somebody else's link) is left alone.
  local tool name dest
  for tool in "$PLUGIN_DIR"/bin/omarchy-captcha-*; do
    name="$(basename "$tool")"
    dest="$BIN_DIR/$name"
    if [[ -L $dest ]] && [[ "$(readlink -f "$dest")" == "$(readlink -f "$tool")" ]]; then
      sudo rm -f "$dest"
      say "removed $dest"
    elif [[ -e $dest ]]; then
      warn "$dest is not a link into this checkout — left alone."
    fi
  done

  # --- userscript symlinks ------------------------------------------------
  unlink_ours "$QUTE_DATA_DIR/userscripts/qute-captcha" "$PLUGIN_DIR/userscripts/qute-captcha"
  unlink_ours "$QUTE_CONFIG_DIR/userscripts/qute-captcha" "$PLUGIN_DIR/userscripts/qute-captcha"

  # --- generated fragment -------------------------------------------------
  # Ours is identified by the marker on its first line, so a fragment a user wrote by hand is left
  # as it is.
  if [[ -f $FRAGMENT ]] && head -1 "$FRAGMENT" | grep -qF "$FRAGMENT_MARKER"; then
    rm -f "$FRAGMENT"
    say "removed $FRAGMENT"
  elif [[ -f $FRAGMENT ]]; then
    warn "$FRAGMENT is not ours — left alone."
  fi

  # --- the source line in the user's config.py ----------------------------
  # Follow a symlinked config.py exactly as install did, then take the appended line back out by
  # exact content. The line is rewritten rather than filtered with `sed -i`, so the user's config is
  # only ever rewritten one line smaller: install appended a blank line, the source line, so the
  # blank line goes with it. Everything else — including whether the file ended in a newline — is
  # restored byte for byte.
  local target_py="$CONFIG_PY"
  if [[ -L $CONFIG_PY ]]; then
    target_py="$(readlink -f "$CONFIG_PY")"
  fi
  if [[ -r $target_py ]] && grep -qF "$SOURCE_LINE" "$target_py"; then
    # install appended "\n" + the source line: a blank line, then the line. Two cases decide
    # whether the original ended in a newline — if that blank line is there, it was appended and
    # the file ended with a newline; if it is not, install's leading newline only terminated the
    # user's last line, so the original had none. Both are reconstructed exactly.
    local kept_file lines=() kept=() line
    local dropped=0 last_source=0 idx total
    kept_file="$(mktemp)"
    mapfile -t lines < "$target_py"
    total=${#lines[@]}
    for (( idx = 0; idx < total; idx++ )); do
      line="${lines[idx]}"
      if [[ $line == "$SOURCE_LINE" ]]; then
        if (( ${#kept[@]} )) && [[ -z ${kept[-1]} ]]; then
          unset 'kept[-1]'
          dropped=1
        fi
        if (( idx == total - 1 )); then
          last_source=1
        fi
        continue
      fi
      kept+=("$line")
    done
    local no_nl=0
    if (( last_source == 1 && dropped == 0 )); then
      no_nl=1
    fi
    local count=${#kept[@]} i
    for (( i = 0; i < count; i++ )); do
      if (( i == count - 1 )) && (( no_nl == 1 )); then
        printf '%s' "${kept[i]}"
      else
        printf '%s\n' "${kept[i]}"
      fi
    done > "$kept_file"
    mv "$kept_file" "$target_py"
    say "removed the source line from $target_py"
  fi

  printf '\nDone. The CLI tools, the userscript links, the fragment and the config.py line are gone.\n'
}

if [[ ${1:-} == --uninstall ]]; then
  uninstall
  exit 0
fi

printf 'omarchy-captcha: installing from %s\n' "$PLUGIN_DIR"

# --- CLI tools -> /usr/local/bin -----------------------------------------
for tool in "$PLUGIN_DIR"/bin/omarchy-captcha-*; do
  name="$(basename "$tool")"
  chmod +x "$tool"
  dest="$BIN_DIR/$name"
  if [[ -L $dest ]] && [[ "$(readlink -f "$dest")" == "$(readlink -f "$tool")" ]]; then
    printf '  %s already linked\n' "$name"
    continue
  fi
  sudo ln -sf "$tool" "$dest"
  printf '  linked %s -> %s\n' "$name" "$dest"
done

# --- userscript -> both qutebrowser userscript dirs ----------------------
mkdir -p "$QUTE_DATA_DIR/userscripts" "$QUTE_CONFIG_DIR/userscripts"
chmod +x "$PLUGIN_DIR/userscripts/qute-captcha"
ln -sf "$PLUGIN_DIR/userscripts/qute-captcha" "$QUTE_DATA_DIR/userscripts/qute-captcha"
ln -sf "$PLUGIN_DIR/userscripts/qute-captcha" "$QUTE_CONFIG_DIR/userscripts/qute-captcha"
printf '  linked qute-captcha userscript\n'

# --- keybindings fragment -------------------------------------------------
# qutebrowser sources exactly one config.py, so a fragment needs one source line for the
# bindings to exist. Follow a symlinked config.py (omarchy-qutebrowser owns it that way) to
# the file that actually defines the config and add the marked line there, so the plugin
# wires itself with no manual step. Idempotent.
TARGET_PY="$CONFIG_PY"
if [[ -L $CONFIG_PY ]]; then
  TARGET_PY="$(readlink -f "$CONFIG_PY")"
  printf '  config.py is a symlink -> %s\n' "$TARGET_PY"
fi

# The prefix is ",v" on purpose. qutebrowser has NO timeout on a partial match, so a binding whose
# first key is itself bound - e.g. ,cc while ,c is reader-factcheck - makes ",c" stop firing and
# swallows the next keypress. Nothing logs an error; the shortcut just goes dead. ",v" is bound to
# nothing on its own, so ,vc/,va/,vs cannot break anything.
STAGE=$(mktemp)
trap 'rm -f "$STAGE"' EXIT
cat > "$STAGE" <<'PY'
# omarchy-captcha keybindings - generated by install.sh
config.bind(",vc", "spawn --userscript qute-captcha", mode="normal")          # noqa: F821
config.bind(",va", "spawn --userscript qute-captcha audio", mode="normal")    # noqa: F821
config.bind(",vs", "spawn --userscript qute-captcha status", mode="normal")   # noqa: F821
PY

CHECK=(--fragment "$STAGE")
if [[ -f $TARGET_PY ]]; then
  CHECK+=(--config "$TARGET_PY")
fi
if ! python3 "$PLUGIN_DIR/tools/check_bindings.py" "${CHECK[@]}"; then
  printf 'install.sh: refusing to install keybindings that collide with %s\n' "$TARGET_PY" >&2
  exit 1
fi
mv "$STAGE" "$FRAGMENT"
printf '  wrote %s\n' "$FRAGMENT"
if [[ -f $TARGET_PY ]]; then
  if grep -q 'captcha-bindings.py' "$TARGET_PY"; then
    printf '  config.py already sources the fragment\n'
  else
    printf '\nconfig.source("captcha-bindings.py")\n' >> "$TARGET_PY"
    printf '  added the source line to %s\n' "$TARGET_PY"
  fi
else
  printf '\nNOTE: no %s found. Add this line where your config is loaded:\n' "$CONFIG_PY"
  printf '    config.source("captcha-bindings.py")\n'
fi

printf '\nDone. Bindings: ,vc solve  ,va audio  ,vs status\n'
printf 'Dependencies: tesseract (required for OCR); ffmpeg + a local STT backend for audio.\n'
